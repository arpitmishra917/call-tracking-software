#!/bin/bash
set -e

echo "[QA-Asterisk] Starting CallFlow QA Asterisk 20 environment initialization..."

if [ -z "$TELNYX_QA_CALLER_SIP_USERNAME" ] || [ -z "$TELNYX_QA_CALLER_SIP_PASSWORD" ]; then
    echo "[QA-Asterisk] ERROR: Caller SIP credentials (TELNYX_QA_CALLER_SIP_USERNAME/TELNYX_QA_CALLER_SIP_PASSWORD) are missing!"
    exit 1
fi

if [ -z "$TELNYX_QA_BUYER_SIP_USERNAME" ] || [ -z "$TELNYX_QA_BUYER_SIP_PASSWORD" ]; then
    echo "[QA-Asterisk] ERROR: Buyer SIP credentials (TELNYX_QA_BUYER_SIP_USERNAME/TELNYX_QA_BUYER_SIP_PASSWORD) are missing!"
    exit 1
fi

ARI_USER="${TELEPHONY_QA_ARI_USERNAME:-callflow_qa}"
ARI_PASS="${TELEPHONY_QA_ARI_PASSWORD:-cfqa_ari_1f044860de198dfa6fd829c7a40f23cbe9ae09b6}"
CALLER_CLI="${TELNYX_QA_CALLER_ID:-+17207159445}"

RAW_IP="${TELEPHONY_QA_EXTERNAL_IP:-$(curl -s -m 2 https://api.ipify.org 2>/dev/null || true)}"
IP_REGEX='^([0-9]{1,3}\.){3}[0-9]{1,3}$'
MEDIA_ADDR_LINE=""
TRANSPORT_EXT_CONF=""

if [[ "$RAW_IP" =~ $IP_REGEX ]]; then
    VALID_IP=true
    IFS='.' read -r -a octets <<< "$RAW_IP"
    for octet in "${octets[@]}"; do
        if (( octet > 255 )); then
            VALID_IP=false
            break
        fi
    done
    if [ "$VALID_IP" = true ]; then
        PUBLIC_IP="$RAW_IP"
        echo "[QA-Asterisk] Validated host external IP for NAT traversal: $PUBLIC_IP"
        MEDIA_ADDR_LINE="media_address=${PUBLIC_IP}"
        TRANSPORT_EXT_CONF="external_media_address=${PUBLIC_IP}
external_signaling_address=${PUBLIC_IP}"
    else
        echo "[QA-Asterisk] WARNING: Public IP candidate has invalid octets ($RAW_IP). Discarding."
    fi
else
    if [ -n "$RAW_IP" ]; then
        echo "[QA-Asterisk] WARNING: Detected malformed public IP response ($RAW_IP). Discarding."
    else
        echo "[QA-Asterisk] External IP detection returned empty; relying on symmetric RTP."
    fi
fi

echo "[QA-Asterisk] Configuring PJSIP transport..."

cat <<EOF > /etc/asterisk/pjsip_transport.conf
; Automatically generated by QA Asterisk entrypoint
[transport-udp]
type=transport
protocol=udp
bind=0.0.0.0:5060
local_net=127.0.0.0/8
local_net=10.0.0.0/8
local_net=172.16.0.0/12
local_net=192.168.0.0/16
${TRANSPORT_EXT_CONF}
EOF

echo "[QA-Asterisk] Configuring PJSIP endpoints for Telnyx..."

cat <<EOF > /etc/asterisk/pjsip_dynamic.conf
; Automatically generated by QA Asterisk entrypoint from environment variables

[telnyx-caller-reg]
type=registration
outbound_auth=telnyx-caller-auth
server_uri=sip:sip.telnyx.com:5060
client_uri=sip:${TELNYX_QA_CALLER_SIP_USERNAME}@sip.telnyx.com:5060
retry_interval=30
max_retries=100
expiration=300
forbidden_retry_interval=60

[telnyx-caller-auth]
type=auth
auth_type=userpass
username=${TELNYX_QA_CALLER_SIP_USERNAME}
password=${TELNYX_QA_CALLER_SIP_PASSWORD}

[telnyx-caller]
type=endpoint
transport=transport-udp
context=from-telnyx-caller
disallow=all
allow=ulaw,alaw,g722
aors=telnyx-caller-aor
outbound_auth=telnyx-caller-auth
from_user=${TELNYX_QA_CALLER_SIP_USERNAME}
from_domain=sip.telnyx.com
callerid=${CALLER_CLI} <${CALLER_CLI}>
direct_media=no
rtp_symmetric=yes
rtp_keepalive=1
force_rport=yes
rewrite_contact=yes
timers=yes
timers_min_se=90
timers_sess_expires=1800
${MEDIA_ADDR_LINE}

[telnyx-buyer-reg]
type=registration
outbound_auth=telnyx-buyer-auth
server_uri=sip:sip.telnyx.com:5060
client_uri=sip:${TELNYX_QA_BUYER_SIP_USERNAME}@sip.telnyx.com:5060
retry_interval=30
max_retries=100
expiration=300
forbidden_retry_interval=60
line=yes
endpoint=telnyx-buyer

[telnyx-buyer-auth]
type=auth
auth_type=userpass
username=${TELNYX_QA_BUYER_SIP_USERNAME}
password=${TELNYX_QA_BUYER_SIP_PASSWORD}

[telnyx-buyer]
type=endpoint
transport=transport-udp
context=from-telnyx-buyer
disallow=all
allow=ulaw,alaw,g722
aors=telnyx-buyer-aor
outbound_auth=telnyx-buyer-auth
from_user=${TELNYX_QA_BUYER_SIP_USERNAME}
from_domain=sip.telnyx.com
direct_media=no
rtp_symmetric=yes
rtp_keepalive=1
force_rport=yes
rewrite_contact=yes
timers=yes
timers_min_se=90
timers_sess_expires=1800
${MEDIA_ADDR_LINE}
EOF

echo "[QA-Asterisk] Configuring ARI authentication..."

cat <<EOF > /etc/asterisk/ari_secrets.conf
; Automatically generated by QA Asterisk entrypoint from environment variables

[${ARI_USER}]
type = user
read_only = no
password = ${ARI_PASS}
EOF

chmod 640 /etc/asterisk/pjsip_dynamic.conf /etc/asterisk/ari_secrets.conf
chown asterisk:asterisk /etc/asterisk/pjsip_dynamic.conf /etc/asterisk/ari_secrets.conf

# Ensure recordings directory is writable
mkdir -p /var/spool/asterisk/recording
chmod 775 /var/spool/asterisk/recording
chown -R asterisk:asterisk /var/spool/asterisk/recording

echo "[QA-Asterisk] QA environment initialized. Launching Asterisk daemon..."

if [ $# -eq 0 ]; then
    set -- /usr/sbin/asterisk -vvvdddf -T -W -U asterisk -p
fi

exec /usr/local/bin/entrypoint.sh "$@"
